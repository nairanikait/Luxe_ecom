const Order = require('../models/orderModel');
const Product = require('../models/productModel');

// Place order
const placeOrder = async (req, res) => {
  try {
    const { form, shippingMethod, paymentMethod, items, subtotal, shippingCost, tax, total } = req.body;
    const userId = req.userId;

    if (!items || items.length === 0 || !form) {
      return res.status(400).json({ success: false, message: 'Missing order details or items.' });
    }

    const orderId = `#ORD-${Math.floor(100000 + Math.random() * 900000)}`;
    const dateStr = new Date().toLocaleDateString('en-US', { month: 'long', day: 'numeric', year: 'numeric' });
    const todayStr = new Date().toLocaleDateString('en-US');
    const totalItems = items.reduce((sum, item) => sum + item.qty, 0);

    const itemsText = items.map(item => `${item.name} x ${item.qty} ${item.variant.split('/')[0].replace('Size: ', '')}`);
    const methodStr = paymentMethod === 0 ? 'Credit Card' : paymentMethod === 1 ? 'PayPal' : paymentMethod === 2 ? 'Apple Pay' : 'COD';
    const paymentStatus = paymentMethod === 3 ? 'Pending' : 'Done';
    const paymentColor = paymentMethod === 3 ? '#ef4444' : '#4b5563';
    
    const statusSub = shippingMethod === 'express' ? 'Est. arrival in 1-2 business days' : 'Est. arrival in 3-5 business days';

    // Decrement stock levels for each item purchased
    for (const item of items) {
      if (item.productId) {
        const product = await Product.findById(item.productId);
        if (product) {
          product.stock = Math.max(0, product.stock - item.qty);
          await product.save();
        }
      }
    }

    const newOrder = await Order.create({
      userId,
      name: `${form.firstName} ${form.lastName}`,
      address: `${form.street}, ${form.apt ? form.apt + ', ' : ''}${form.city}, ${form.state}, US, ${form.zip}\n${form.email}`,
      itemsText,
      meta: {
        items: totalItems,
        method: methodStr,
        payment: paymentStatus,
        date: todayStr
      },
      paymentColor,
      total,
      status: 'Order Placed',
      statusSub,
      img: items[0]?.img || 'https://images.unsplash.com/photo-1539533018447-63fcce2678e3?w=200&q=80&fit=crop',
      statusColor: '#4b5563'
    });

    // Override the mock id generated by mongodb so it matches the human readable orderId
    newOrder.id = orderId;
    await Order.findByIdAndUpdate(newOrder._id, { id: orderId });

    res.status(201).json({ success: true, order: newOrder });
  } catch (error) {
    console.error('Place order error:', error.message);
    res.status(500).json({ success: false, message: error.message });
  }
};

// Get user orders (customer side)
const userOrders = async (req, res) => {
  try {
    const orders = await Order.find({ userId: req.userId }).sort({ createdAt: -1 });
    res.json({ success: true, orders });
  } catch (error) {
    console.error('User orders error:', error.message);
    res.status(500).json({ success: false, message: error.message });
  }
};

// Get all orders (admin side)
const allOrders = async (req, res) => {
  try {
    const orders = await Order.find({}).sort({ createdAt: -1 });
    res.json({ success: true, orders });
  } catch (error) {
    console.error('All orders error:', error.message);
    res.status(500).json({ success: false, message: error.message });
  }
};

// Update order status (admin side)
const updateStatus = async (req, res) => {
  try {
    const { orderId, status } = req.body;

    const statusColors = {
      'Order Placed': '#4b5563',
      'Processing': '#f59e0b',
      'Shipped': '#2563eb',
      'Delivered': '#16a34a'
    };

    const order = await Order.findOne({ id: orderId });
    if (!order) {
      return res.status(404).json({ success: false, message: 'Order not found.' });
    }

    order.status = status;
    order.statusColor = statusColors[status] || '#4b5563';
    if (status === 'Delivered') {
      order.statusSub = 'Delivered';
    }

    await order.save();

    res.json({ success: true, message: 'Order status updated successfully.', order });
  } catch (error) {
    console.error('Update status error:', error.message);
    res.status(500).json({ success: false, message: error.message });
  }
};

module.exports = {
  placeOrder,
  userOrders,
  allOrders,
  updateStatus
};
